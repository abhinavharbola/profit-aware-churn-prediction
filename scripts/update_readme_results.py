import os
import sys
import pickle
import argparse
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from config import ARTIFACTS_DIR, PROCESSED_DIR, ROOT_DIR

START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"


def load_pickle(name):
    path = os.path.join(ARTIFACTS_DIR, name)
    if not os.path.exists(path):
        raise FileNotFoundError(f"{path} not found. Run scripts/run_pipeline.py first.")
    with open(path, "rb") as f:
        return pickle.load(f)


def to_markdown_table(df):
    header = "| " + " | ".join(df.columns) + " |"
    divider = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, divider] + rows)


def build_block():
    metrics = load_pickle("metrics.pkl")
    threshold = load_pickle("optimal_threshold.pkl")
    split = load_pickle("split_metadata.pkl")

    comparison_path = os.path.join(PROCESSED_DIR, "profit_comparison.csv")
    if not os.path.exists(comparison_path):
        raise FileNotFoundError(f"{comparison_path} not found. Run scripts/run_pipeline.py first.")
    comparison = pd.read_csv(comparison_path)
    comparison["Net Campaign Profit"] = comparison["Net Campaign Profit"].map(lambda v: f"£{v:,.0f}")

    total = split["train_rows"] + split["validation_rows"] + split["test_rows"] + split.get("purged_rows", 0)

    summary = pd.DataFrame({
        "Metric": [
            "PR-AUC (final temporal test, raw scores)",
            "Brier score (final temporal test, calibrated)",
            "Locked profit threshold (selected on validation, cross-fitted)",
        ],
        "Value": [f"{metrics['pr_auc']:.4f}", f"{metrics['brier_score']:.4f}", f"{float(threshold):.2f}"],
    })

    splits = pd.DataFrame({
        "Split": ["Train", "Validation", "Test", "Purged by embargo"],
        "Rows": [
            f"{split['train_rows']:,}",
            f"{split['validation_rows']:,} ({split['tuning_rows']:,} tuning, {split['calibration_rows']:,} calibration)",
            f"{split['test_rows']:,}",
            f"{split.get('purged_rows', 0):,}",
        ],
        "Share": [
            f"{split['train_rows'] / total:.1%}",
            f"{split['validation_rows'] / total:.1%}",
            f"{split['test_rows'] / total:.1%}",
            f"{split.get('purged_rows', 0) / total:.1%}",
        ],
    })

    lines = [
        START,
        to_markdown_table(summary),
        "",
        f"Split sizes (embargo of {split.get('embargo_days', 'n/a')} days at each boundary):",
        "",
        to_markdown_table(splits),
        "",
        "Profit comparison on the final test set:",
        "",
        to_markdown_table(comparison),
        "",
        "Generated by `scripts/update_readme_results.py` from the artifacts of the last `scripts/run_pipeline.py` run. Re-run both after changing the data, seed, windowing, or financial assumptions.",
        END,
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Write the latest pipeline results into the README results block.")
    parser.add_argument("--readme", default=os.path.join(ROOT_DIR, "README.md"))
    args = parser.parse_args()

    with open(args.readme, "r", encoding="utf-8") as f:
        text = f.read()

    if START not in text or END not in text:
        raise ValueError(f"{args.readme} is missing the {START} / {END} markers.")

    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new_text = head + build_block() + tail

    with open(args.readme, "w", encoding="utf-8") as f:
        f.write(new_text)

    print(f"Updated results block in {args.readme}")


if __name__ == "__main__":
    main()
